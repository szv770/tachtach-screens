// Dev tool (not run by the app or the tests): turns raw Hebcal / Chabad.org dumps into the small committed
// fixtures test/localData.test.js compares the local calculation against.
//   node scripts/make-parity-fixtures.mjs <dir with hc/all.json, hc/sedra.json, z/*.xml, z2/<zip>/*.xml> <out dir>
// Raw dumps (any machine with internet):
//   hc/all.json   merge of  https://www.hebcal.com/converter?cfg=json&start=A&end=B&g2h=1  ("hdates"), windows of <=170 days, 2019-01-01..2036-12-31
//   hc/sedra.json {year: [[date,title,hebrew],..]} from https://www.hebcal.com/hebcal?v=1&cfg=json&year=Y&month=x&s=on&i=off  (category parashat), Y=1990..2079
//   z/ z2/        https://www.chabad.org/tools/rss/zmanim.xml?locationid=<zip>&locationtype=2&tdate=YYYY-MM-DD  saved as <date>.xml
import fs from 'fs';
import path from 'path';
import { parseZmanimRSS } from '../src/fetchers/chabad.js';

const [, , inDir, outDir] = process.argv;
const all = JSON.parse(fs.readFileSync(path.join(inDir, 'hc/all.json'), 'utf8'));
const dates = Object.keys(all).sort();
const strip = (s) => s.replace(/[֑-ׇ]/g, '');
const monthNames = [...new Set(dates.map((d) => all[d].hm))];
const he = { day: {}, month: {}, year: {} };
const rows = dates.map((d) => {
  const h = all[d];
  he.day[h.hd] = strip(h.heDateParts.d); he.month[h.hm] = strip(h.heDateParts.m); he.year[h.hy] = strip(h.heDateParts.y);
  return [h.hy, monthNames.indexOf(h.hm), h.hd];
});
const events = {};
for (const d of dates) {
  const ev = all[d].events.filter((e) => !/^(Molad|Shabbat Mevarchim|Yom HaShoah|Yom HaZikaron|Yom HaAtzma|Leil Selichot|Sigd|Yom HaAliyah|Chag HaBanot|Purim Meshulash|Swords of Iron|Rosh Hashana LaBehemot|Parashat )/.test(e));
  if (ev.length) events[d] = ev;
}
const sedra = JSON.parse(fs.readFileSync(path.join(inDir, 'hc/sedra.json'), 'utf8'));
const names = [];
const shabbosim = [];
for (const y of Object.keys(sedra)) for (const [d, t] of sedra[y]) {
  let i = names.indexOf(t); if (i < 0) { i = names.length; names.push(t); }
  shabbosim.push(`${d}:${i}`);
}
const hebrewByTitle = {};
for (const y of Object.keys(sedra)) for (const [, t, hh] of sedra[y]) hebrewByTitle[t] = hh;
fs.writeFileSync(path.join(outDir, 'hebcal-parity.json'), JSON.stringify({
  note: 'Hebcal converter/parsha output, 2019-2036 (days) and 1990-2079 (Shabbosim). Generated by scripts/make-parity-fixtures.mjs.',
  start: dates[0], months: monthNames, rows, he, events, parsha: { names, hebrew: names.map((t) => hebrewByTitle[t]), shabbosim },
}));

const sets = [
  { dir: 'z', zip: '33139', lat: 25.7873, lon: -80.1564, tz: 'America/New_York' },
  { dir: 'z2/11213', zip: '11213', lat: 40.67, lon: -73.9366, tz: 'America/New_York' },
  { dir: 'z2/90210', zip: '90210', lat: 34.0901, lon: -118.4065, tz: 'America/Los_Angeles' },
  { dir: 'z2/60601', zip: '60601', lat: 41.8858, lon: -87.6181, tz: 'America/Chicago', candleMinutes: 20 },
  { dir: 'z2/98101', zip: '98101', lat: 47.6114, lon: -122.3305, tz: 'America/Los_Angeles' },
];
const zm = sets.map((s) => {
  const days = {};
  for (const fn of fs.readdirSync(path.join(inDir, s.dir)).filter((f) => f.endsWith('.xml')).sort()) {
    days[fn.slice(0, 10)] = parseZmanimRSS(fs.readFileSync(path.join(inDir, s.dir, fn), 'utf8'));
  }
  return { zip: s.zip, lat: s.lat, lon: s.lon, timezone: s.tz, candleMinutes: s.candleMinutes ?? null, days };
});
fs.writeFileSync(path.join(outDir, 'zmanim-parity.json'), JSON.stringify({ note: 'Chabad.org zmanim RSS output (parsed), see scripts/make-parity-fixtures.mjs.', sets: zm }));
console.log({ days: dates.length, eventsDays: Object.keys(events).length, shabbosim: shabbosim.length });
